"""Generate the SDK based on the aas-core-meta model and the snippets."""

import argparse
import os
import pathlib
import re
import subprocess
import sys

# NOTE (aaronzi, 2026-11-05):
# aas-core-codegen does not emit any copyright or license information, so we
# prepend the header to the generated Java files ourselves. Otherwise, the headers
# would be lost on every re-generation.
#
# REUSE-IgnoreStart
_LICENSE_HEADER = """\
// SPDX-FileCopyrightText: 2023 aas-core3.0-java AUTHORS
//
// SPDX-License-Identifier: MIT

"""
# REUSE-IgnoreEnd

_LEADING_SPDX_COMMENTS_RE = re.compile(r"\A(?://\s*(?:SPDX-[A-Za-z-]+:.*)?\n|\n)*")


def _prepend_license_header(text: str) -> str:
    """Replace any leading SPDX comment block in ``text`` with our license header."""
    return _LICENSE_HEADER + _LEADING_SPDX_COMMENTS_RE.sub("", text, count=1)


def _add_license_headers(sdk_module_dir: pathlib.Path) -> None:
    """
    Prepend the license header to all the files generated by aas-core-codegen.

    Not all the generated files carry the "automatically generated by
    aas-core-codegen" marker (e.g., the builders in ``generation/`` do not), so we
    add the header to all the Java files in the output directory.
    """
    for path in sorted(sdk_module_dir.rglob("*.java")):
        text = path.read_text(encoding="utf-8")
        path.write_text(_prepend_license_header(text), encoding="utf-8")


def _generate_sdk(
    meta_model_path: pathlib.Path,
    snippet_path: pathlib.Path,
    sdk_path: pathlib.Path,
) -> None:
    subprocess.run(
        [
            "aas-core-codegen",
            "--model_path",
            str(meta_model_path),
            "--snippets_dir",
            str(snippet_path),
            "--output_dir",
            str(sdk_path / "src/main/java/aas_core/aas3_0"),
            "--target",
            "java",
        ],
        check=True,
    )

    _add_license_headers(sdk_path / "src/main/java/aas_core/aas3_0")


def main() -> int:
    """Execute the main routine."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--meta_model", type=pathlib.Path, required=True)
    parser.add_argument("--target", type=pathlib.Path, required=True)
    args = parser.parse_args()

    this_dir = pathlib.Path(os.path.realpath(__file__)).parent

    snippet_dir = this_dir / "snippets"

    _generate_sdk(args.meta_model, snippet_dir, this_dir.parent.parent)

    return 0


if __name__ == "__main__":
    sys.exit(main())
